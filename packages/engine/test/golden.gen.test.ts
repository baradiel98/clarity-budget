import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { it } from 'vitest';
import { buildDashboard } from '../src';
import { GOLDEN_SCENARIOS, goldenSummary } from '../src/golden/scenarios';
it.skipIf(!process.env.GEN_GOLDEN)('generate golden expected outputs', () => {
  const out = Object.fromEntries(Object.entries(GOLDEN_SCENARIOS).map(([k, v]) => [k, goldenSummary(buildDashboard(v))]));
  writeFileSync(join(__dirname, '../src/golden/expected.ts'), `// Generated by GEN_GOLDEN=1 npx vitest run packages/engine/test/golden.gen.test.ts — review diffs before committing.\nexport const GOLDEN_EXPECTED: Record<string, unknown> = ${JSON.stringify(out, null, 2)};\n`);
});
